#!/usr/bin/env python3
"""Fractional-delay filters for 56 MHz overclocked and 30.72 MHz standard modes.

Each sample-rate profile minimizes complex response error with exactly unity
DC gain. A dual-port ROM serves each pair of targets. Storing the complete table avoids
coefficient-reversal multiplexers. Coefficients use signed Q2.16.
"""

from functools import lru_cache
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]


@lru_cache(maxsize=2)
def table(fast=True):
    rate = 160e6 if fast else 61.44e6
    bandwidth = 56e6 if fast else 30.72e6
    taps = 6 if fast else 8
    center = taps // 2 - 1
    omega = 2 * np.pi * np.linspace(0, bandwidth / 2, 1025) / rate
    basis = np.exp(-1j * omega[:, None] * np.arange(taps))
    other = [k for k in range(taps) if k != center]
    a = basis[:, other] - basis[:, center, None]
    fractions = np.arange(513) / 1024
    b = np.exp(-1j * omega[:, None] * (center + fractions)) - basis[:, center, None]
    fitted = np.linalg.lstsq(
        np.vstack((a.real, a.imag)), np.vstack((b.real, b.imag)), rcond=None
    )[0]
    h = np.empty((taps, 513))
    h[other] = fitted
    h[center] = 1 - fitted.sum(axis=0)
    h[:, 512] = (h[:, 512] + h[::-1, 512]) / 2
    words = np.rint(h.T * 65536).astype(np.int64)
    words[:512, center] += 65536 - words[:512].sum(axis=1)
    correction = (65536 - words[512].sum()) // 2
    words[512, center:center+2] += correction
    return np.vstack((words, words[511:0:-1, ::-1]))


def coefficients(index, fast=True):
    values = [int(x) for x in table(fast)[index]]
    return values + [0] * (8 - len(values))


def main():
    lines = [
        "// Generated by scripts/generate_fractional_rom.py. Do not edit by hand.",
        "// Two independent reads share one complete coefficient table.",
        '(* keep_hierarchy = "yes" *) module fractional_rom(input wire clk, fast_profile,',
        "    input wire [9:0] address0, address1,",
        "    output reg [143:0] coefficients0, coefficients1);",
        '(* ram_style = "block" *) reg [143:0] memory[0:2047];',
        "reg [10:0] address_pipe0[0:4], address_pipe1[0:4];",
        "initial begin",
    ]
    for fast in (False, True):
        for address in range(1024):
            packed = sum((value & 0x3FFFF) << (18 * k)
                         for k, value in enumerate(coefficients(address, fast)))
            lines.append(f"    memory[{1024*int(fast)+address}] = 144'h{packed:036x};")
    lines += [
        "end",
        "always @(posedge clk) begin",
        "    // Delay narrow addresses to align coefficients with the sample reads.",
        "    address_pipe0[0] <= {fast_profile, address0};",
        "    address_pipe1[0] <= {fast_profile, address1};",
        "    for (integer p = 1; p < 5; p = p + 1) begin",
        "        address_pipe0[p] <= address_pipe0[p-1];",
        "        address_pipe1[p] <= address_pipe1[p-1];",
        "    end",
        "    coefficients0 <= memory[address_pipe0[4]];",
        "    coefficients1 <= memory[address_pipe1[4]];",
        "end",
        "endmodule",
    ]
    path = ROOT / "rtl/fractional_rom.sv"
    text = "\n".join(lines) + "\n"
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


if __name__ == "__main__":
    main()
